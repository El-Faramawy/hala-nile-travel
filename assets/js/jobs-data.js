// دالة البحث وتصفية الوظائف
function filterJobs(category = 'all', searchQuery = '') {
  return IT_JOBS.filter(job => {
    const matchCategory = (category === 'all' || job.category === category);
    const search = searchQuery.trim().toLowerCase();
    const matchSearch = !search || 
      job.title.toLowerCase().includes(search) || 
      job.city.toLowerCase().includes(search) || 
      job.description.toLowerCase().includes(search) ||
      job.categoryName.toLowerCase().includes(search);
    return matchCategory && matchSearch;
  });
}

